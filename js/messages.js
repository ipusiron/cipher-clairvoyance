export const MESSAGES = { ja: JA, en: EN };
export const LANGUAGES = ['ja', 'en'];

let current = 'ja';

export function setLanguage(lang) {
  current = LANGUAGES.includes(lang) ? lang : 'ja';
  return current;
}

export function getLanguage() {
  return current;
}

export function t(key, params = {}, lang = current) {
  const dict = MESSAGES[lang] || JA;
  const template = dict[key] ?? JA[key] ?? key;
  const sep = dict['list.sep'] ?? JA['list.sep'];
  return template.replace(/\{(\w+)\}/g, (m, name) => {
    if (!(name in params)) return m;
    const v = params[name];
    return Array.isArray(v) ? v.join(sep) : String(v);
  });
}
